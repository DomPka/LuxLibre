"""Generate a minimal C register header for a tinyAVR 0/1-series chip from Microchip's
ATDF device description (XML).

Why: the avr-libc shipped with many Linux distributions (2.0.0) has no header for the
ATtiny1616. The ATDF files are published by Microchip in its device packs and are also
bundled with the avr-device Rust crate (vendor/attiny1617.atdf). The ATtiny1616 and
ATtiny1617 share every register address; the 1617 only has more pins.

    python3 atdf_to_header.py attiny1617.atdf tiny1x_io.h

The output defines, for the selected peripherals:
    <INSTANCE>_<REGISTER>                 the register (volatile access)
    <MODULE>_<FIELD>_bm / _gm / _gp       bit mask / group mask / group position
    <MODULE>_<FIELD>_<VALUE>_gc           group configuration value (already shifted)
    <INSTANCE>_<NAME>_vect_num            interrupt vector numbers
and the memory map (EEPROM, SRAM, flash).
"""
import sys
import xml.etree.ElementTree as ET

INSTANCES = ["CPU", "CLKCTRL", "SLPCTRL", "RSTCTRL", "WDT", "BOD", "VREF", "PORTA", "PORTB",
             "PORTC", "PORTMUX", "ADC0", "TCA0", "TCB0", "RTC", "NVMCTRL", "SIGROW", "USART0"]
MODE_PREFERRED = {"TCA": "SINGLE", "USART": "NORMAL"}


def as_int(s):
    return int(s, 0)


def main(src, dst):
    root = ET.parse(src).getroot()
    device = root.find("devices/device")
    name = device.get("name")
    modules = {m.get("name"): m for m in root.findall("modules/module")}
    value_groups = {}
    for m in modules.values():
        for vg in m.findall("value-group"):
            value_groups[vg.get("name")] = [(v.get("name"), as_int(v.get("value"))) for v in vg.findall("value")]

    out = []
    w = out.append
    w("// SPDX-License-Identifier: Apache-2.0")
    w("// Generated by atdf_to_header.py from the Microchip ATDF of the %s - do not edit." % name)
    w("// Device description: Copyright (c) 2018 Microchip Technology Inc., Apache License 2.0")
    w("// (LICENSES/Apache-2.0.txt), as distributed in the avr-device crate's vendor folder.")
    w("// Register addresses and bit names are taken unchanged from the device description.")
    w("#pragma once")
    w("#include <stdint.h>")
    w("#define LX_SFR8(a) (*(volatile uint8_t *)(a))")
    w("#define LX_SFR16(a) (*(volatile uint16_t *)(a))")
    w("")

    # memory map
    for seg in device.findall("address-spaces/address-space/memory-segment"):
        n = seg.get("name")
        if n in ("EEPROM", "INTERNAL_SRAM", "PROGMEM", "MAPPED_PROGMEM", "SIGNATURES", "USER_SIGNATURES"):
            w("#define MEM_%s_START 0x%04X" % (n, as_int(seg.get("start"))))
            w("#define MEM_%s_SIZE 0x%04X" % (n, as_int(seg.get("size"))))
            if seg.get("pagesize"):
                w("#define MEM_%s_PAGE_SIZE %d" % (n, as_int(seg.get("pagesize"))))
    w("")

    defined = {}

    def define(key, val, comment=""):
        if key in defined:
            if defined[key] != val:
                w("// conflicting definition skipped: %s = %s (kept %s)" % (key, val, defined[key]))
            return
        defined[key] = val
        w("#define %s %s%s" % (key, val, ("  // " + comment) if comment else ""))

    for periph in device.findall("peripherals/module"):
        mname = periph.get("name")
        for inst in periph.findall("instance"):
            iname = inst.get("name")
            if iname not in INSTANCES:
                continue
            rg = inst.find("register-group")
            base = as_int(rg.get("offset"))
            group_name = rg.get("name-in-module")
            module = modules[mname]
            group = None
            for g in module.findall("register-group"):
                if g.get("name") == group_name:
                    group = g
            if group is None:
                continue
            pref_mode = MODE_PREFERRED.get(mname)
            w("// ---- %s (%s) @ 0x%04X ----" % (iname, mname, base))
            for reg in group.findall("register"):
                modes = reg.get("modes")
                if modes and pref_mode and pref_mode not in modes.split():
                    continue
                rname = reg.get("name")
                size = as_int(reg.get("size"))
                addr = base + as_int(reg.get("offset"))
                prefix_inst = iname + ("_" + pref_mode if modes and pref_mode else "")
                prefix_mod = mname + ("_" + pref_mode if modes and pref_mode else "")
                acc = "LX_SFR16" if size == 2 else "LX_SFR8"
                define("%s_%s" % (prefix_inst, rname), "%s(0x%04X)" % (acc, addr))
                if size == 2:
                    define("%s_%sL" % (prefix_inst, rname), "LX_SFR8(0x%04X)" % addr)
                    define("%s_%sH" % (prefix_inst, rname), "LX_SFR8(0x%04X)" % (addr + 1))
                for bf in reg.findall("bitfield"):
                    fname = bf.get("name")
                    mask = as_int(bf.get("mask"))
                    pos = (mask & -mask).bit_length() - 1
                    if mask & (mask - 1) == 0:
                        define("%s_%s_bm" % (prefix_mod, fname), "0x%02X" % mask)
                        define("%s_%s_bp" % (prefix_mod, fname), "%d" % pos)
                    else:
                        define("%s_%s_gm" % (prefix_mod, fname), "0x%02X" % mask)
                        define("%s_%s_gp" % (prefix_mod, fname), "%d" % pos)
                    vg = bf.get("values")
                    if vg and vg in value_groups:
                        for vname, val in value_groups[vg]:
                            define("%s_%s_gc" % (vg, vname), "(0x%02X << %d)" % (val, pos))
            w("")

    w("// ---- interrupt vectors ----")
    seen = set()
    for intr in device.findall("interrupts/interrupt"):
        inst = intr.get("module-instance")
        n = intr.get("name")
        key = "%s_%s_vect_num" % (inst, n)
        if key in seen:
            continue
        seen.add(key)
        w("#define %s %s" % (key, intr.get("index")))
    count = max(as_int(i.get("index")) for i in device.findall("interrupts/interrupt")) + 1
    w("#define LX_VECTOR_COUNT %d" % count)
    w("")
    open(dst, "w").write("\n".join(out) + "\n")
    print("wrote %s (%d definitions)" % (dst, len(defined)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1], sys.argv[2])
